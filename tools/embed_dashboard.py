"""Embed local, compressed assets in flash; no filesystem upload or CDN needed."""
from pathlib import Path
import gzip
import hashlib
import json
import base64

if "Import" in globals():
    Import("env")
    ROOT = Path(env.subst("$PROJECT_DIR"))
else:
    ROOT = Path(__file__).resolve().parents[1]
ASSETS = [
    ("/", "index.html", "text/html; charset=utf-8"),
    ("/app.css", "app.css", "text/css; charset=utf-8"),
    ("/app.js", "app.js", "text/javascript; charset=utf-8"),
    ("/font.woff2", "font.woff2", "font/woff2"),
    ("/font-vi.woff2", "font-vi.woff2", "font/woff2"),
    ("/iuh-logo.svg", "iuh-logo.svg", "image/svg+xml"),
]


def embed():
    lines = ["// Generated by tools/embed_dashboard.py. Edit dashboard/ sources.",
             "#pragma once", "#include <stdint.h>", "#include <stddef.h>",
             "struct DashboardAsset { const char *path; const char *mime; const uint8_t *bytes; size_t length; };"]
    manifest = {}
    for index, (route, name, mime) in enumerate(ASSETS):
        data = (ROOT / "dashboard" / name).read_bytes()
        packed = gzip.compress(data, compresslevel=9, mtime=0)
        lines.append(f"static const uint8_t DASH_ASSET_{index}[] = {{")
        for offset in range(0, len(packed), 24):
            lines.append(",".join(str(b) for b in packed[offset:offset + 24]) + ",")
        lines.append("};")
        manifest[name] = {"bytes": len(data), "gzip_bytes": len(packed),
                          "sha256": hashlib.sha256(data).hexdigest()}
    lines.append("static const DashboardAsset DASHBOARD_ASSETS[] = {")
    for index, (route, name, mime) in enumerate(ASSETS):
        lines.append(f'{{"{route}","{mime}",DASH_ASSET_{index},sizeof(DASH_ASSET_{index})}},')
    lines.append("};\n")
    target = ROOT / "dashboard_assets.h"
    output = "\n".join(lines)
    if not target.exists() or target.read_text() != output:
        target.write_text(output, encoding="ascii")
    (ROOT / "dashboard" / "asset-manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="ascii")
    # A separate, self-contained preview can be opened as a file without a server.
    css = (ROOT / "dashboard/app.css").read_text(encoding="utf-8")
    for font in ("font.woff2", "font-vi.woff2"):
        encoded = base64.b64encode((ROOT / "dashboard" / font).read_bytes()).decode("ascii")
        css = css.replace("/" + font, "data:font/woff2;base64," + encoded)
    js = (ROOT / "dashboard/app.js").read_text(encoding="utf-8").replace(
        "const demo = new URLSearchParams(location.search).get('preview') === '1';",
        "const demo = true;")
    preview = (ROOT / "dashboard/index.html").read_text(encoding="utf-8")
    logo = base64.b64encode((ROOT / "dashboard/iuh-logo.svg").read_bytes()).decode("ascii")
    preview = preview.replace('/iuh-logo.svg', 'data:image/svg+xml;base64,' + logo)
    preview = preview.replace('<link rel="stylesheet" href="/app.css">', '<style>' + css + '</style>')
    preview = preview.replace('<script type="module" src="/app.js"></script>',
                              '<script type="module">' + js + '</script>')
    preview = preview.replace('<head>', '<head><meta http-equiv="Content-Security-Policy" '
        'content="default-src \'none\'; script-src \'unsafe-inline\'; style-src \'unsafe-inline\'; '
        'font-src data:; img-src data:; connect-src \'none\'">')
    preview = preview.replace('href="/" aria-label=', 'href="preview.html" aria-label=')
    (ROOT / "dashboard/preview.html").write_text(preview, encoding="utf-8")
    print("Dashboard: embedded", sum(v["gzip_bytes"] for v in manifest.values()), "bytes")


embed()
